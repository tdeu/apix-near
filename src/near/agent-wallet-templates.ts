export function vaultModule(): string {
  return `// Generated by APIX (apix add agent-wallet --chain near).
// Server-only: the agent key never reaches the browser.
//
// The agent signs with a function-call key on the vault account. That key can
// only call pay and request_approval on the vault contract, and the contract
// enforces the owner's limits (per payment, per day, allowlist, pause).
// A leaked key can at most spend today's remaining allowance to allowlisted
// receivers, and the owner can pause the vault or revoke the key at any time.
import 'server-only';
import { Account, JsonRpcProvider, teraToGas } from 'near-api-js';
import type { KeyPairString } from 'near-api-js';

const RPC: Record<string, string> = {
  testnet: 'https://rpc.testnet.near.org',
  mainnet: 'https://rpc.mainnet.near.org',
};

function config() {
  const network = process.env.NEAR_NETWORK ?? 'testnet';
  const vaultId = process.env.NEAR_VAULT_ID;
  const agentKey = process.env.NEAR_AGENT_PRIVATE_KEY;
  if (!vaultId || !agentKey) {
    throw new Error('NEAR_VAULT_ID and NEAR_AGENT_PRIVATE_KEY must be set (apix near vault create writes them to .env.local).');
  }
  const provider = new JsonRpcProvider({ url: process.env.NEAR_RPC_URL ?? RPC[network] ?? RPC.testnet });
  return { network, vaultId, agentKey: agentKey as KeyPairString, provider };
}

// No bigint literals (10n): Next.js projects default to an ES2017 TypeScript target
const YOCTO = BigInt('1000000000000000000000000');

/** "0.25" NEAR -> yoctoNEAR, refusing anything that isn't a plain positive amount */
export function parseNear(amount: string | number): bigint {
  const text = String(amount).trim();
  if (!/^\\d+(\\.\\d{1,24})?$/.test(text)) throw new Error(\`Invalid NEAR amount: \${text}\`);
  const [whole, frac = ''] = text.split('.');
  return BigInt(whole) * YOCTO + BigInt(frac.padEnd(24, '0'));
}

export function formatNear(yocto: string | bigint): string {
  const value = BigInt(yocto);
  const frac = (value % YOCTO).toString().padStart(24, '0').replace(/0+$/, '').slice(0, 5);
  return frac ? \`\${value / YOCTO}.\${frac}\` : (value / YOCTO).toString();
}

export interface VaultStatus {
  paused: boolean;
  policy: { per_tx_limit: string; daily_limit: string };
  spent_in_window: string;
  remaining_today: string;
  window_resets_at_ns: number;
  available_balance: string;
  payments_made: number;
  pending_requests: number;
}

export async function getVaultStatus(): Promise<VaultStatus & { vaultId: string; network: string; allowlist: string[] }> {
  const { provider, vaultId, network } = config();
  const [status, allowlist] = await Promise.all([
    provider.callFunction<VaultStatus>({ contractId: vaultId, method: 'get_status', args: {} }),
    provider.callFunction<string[]>({ contractId: vaultId, method: 'get_allowlist', args: {} }),
  ]);
  return { ...(status as VaultStatus), allowlist: (allowlist as string[]) ?? [], vaultId, network };
}

export type PaymentOutcome =
  | { status: 'paid'; txHash: string }
  | { status: 'pending_approval'; requestId: number; reason: string; txHash: string }
  | { status: 'refused'; reason: string };

/**
 * Pays from the vault. The contract is the authority: this checks first with
 * the free check_payment view so a refused payment costs no gas, and the
 * contract checks again when it executes.
 * Over-limit payments to allowlisted receivers are filed for the owner's
 * approval when escalate is true.
 */
export async function payFromVault(input: { to: string; amountNear: string | number; memo?: string; escalate?: boolean }): Promise<PaymentOutcome> {
  const { provider, vaultId, agentKey } = config();
  const amount = parseNear(input.amountNear);
  const args = { receiver_id: input.to, amount: amount.toString() };
  // check_payment returns null when the payment would go through, or the reason it wouldn't
  const reason = (await provider.callFunction<string>({ contractId: vaultId, method: 'check_payment', args })) ?? null;
  const agent = new Account(vaultId, provider, agentKey);

  if (reason === null) {
    const result = await agent.callFunctionRaw({
      contractId: vaultId,
      methodName: 'pay',
      args: { ...args, memo: input.memo ?? null },
      gas: teraToGas('30'),
      waitUntil: 'FINAL',
    });
    return { status: 'paid', txHash: result.transaction.hash };
  }

  const amountProblem = /per-transaction limit|daily limit/.test(reason);
  if (!input.escalate || !amountProblem) return { status: 'refused', reason };

  const result = await agent.callFunctionRaw({
    contractId: vaultId,
    methodName: 'request_approval',
    args: { ...args, memo: input.memo ?? null, reason },
    gas: teraToGas('30'),
    waitUntil: 'FINAL',
  });
  const raw = (result.status as { SuccessValue?: string }).SuccessValue ?? '';
  const requestId = Number(JSON.parse(Buffer.from(raw, 'base64').toString() || '0'));
  return { status: 'pending_approval', requestId, reason, txHash: result.transaction.hash };
}
`;
}

