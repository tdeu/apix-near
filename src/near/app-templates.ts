// src/near/app-templates.ts
// Files `apix add wallet|token --chain near` writes into a Next.js app.
// The wallet provider follows NEAR's reference (near-examples/hello-near-examples,
// NEAR Connect). Users sign with their own wallet: the app never holds a key.

export function configModule(): string {
  return `// Generated by APIX. Public settings only: never put a private key here.
export type NearNetwork = 'testnet' | 'mainnet';

export const NEAR_NETWORK: NearNetwork =
  process.env.NEXT_PUBLIC_NEAR_NETWORK === 'mainnet' ? 'mainnet' : 'testnet';

export const RPC_URLS: Record<NearNetwork, string[]> = {
  mainnet: ['https://free.rpc.fastnear.com', 'https://rpc.mainnet.near.org'],
  testnet: ['https://test.rpc.fastnear.com', 'https://rpc.testnet.near.org'],
};

export const EXPLORER: Record<NearNetwork, string> = {
  mainnet: 'https://nearblocks.io',
  testnet: 'https://testnet.nearblocks.io',
};

/** Contract the app talks to by default (set NEXT_PUBLIC_NEAR_CONTRACT_ID) */
export const NEAR_CONTRACT_ID = process.env.NEXT_PUBLIC_NEAR_CONTRACT_ID ?? '';

/** NEP-141 token (set NEXT_PUBLIC_NEAR_TOKEN_ID, written by apix near token create) */
export const NEAR_TOKEN_ID = process.env.NEXT_PUBLIC_NEAR_TOKEN_ID ?? '';

/** 30 TGas, enough for a simple call */
export const DEFAULT_GAS = '30000000000000';
`;
}

export function providerModule(configImport: string): string {
  return `'use client';
// Generated by APIX (apix add wallet --chain near).
// Wallet login with NEAR Connect. Users sign with their own wallet, so the app
// never sees a private key. Wrap your layout in <NearProvider>, then use
// useNearWallet() in any client component.
import { createContext, type PropsWithChildren, useCallback, useContext, useEffect, useMemo, useState } from 'react';
import { FailoverRpcProvider, getTransactionLastResult, JsonRpcProvider } from 'near-api-js';
import { NearConnector, type EventMap } from '@hot-labs/near-connect';
import { DEFAULT_GAS, NEAR_NETWORK, RPC_URLS } from '${configImport}';

type Wallet = Awaited<ReturnType<NearConnector['wallet']>>;

export interface FunctionCall {
  methodName: string;
  args?: Record<string, unknown>;
  /** Gas in units, as a string (default 30 TGas) */
  gas?: string;
  /** Attached deposit in yoctoNEAR, as a string (default "0") */
  deposit?: string;
}

interface NearContextValue {
  loading: boolean;
  accountId: string;
  network: string;
  signIn: () => Promise<void>;
  signOut: () => Promise<void>;
  /** Read-only call, no wallet needed */
  view: <T = unknown>(contractId: string, method: string, args?: Record<string, unknown>) => Promise<T>;
  /** One transaction to one contract, signed by the user's wallet */
  call: (contractId: string, calls: FunctionCall[]) => Promise<{ hash: string; result: unknown }>;
}

const NearContext = createContext<NearContextValue | undefined>(undefined);

export function NearProvider({ children }: PropsWithChildren) {
  const connector = useMemo(
    () => new NearConnector({ network: NEAR_NETWORK, providers: { mainnet: RPC_URLS.mainnet, testnet: RPC_URLS.testnet } }),
    []
  );
  const rpc = useMemo(
    () => new FailoverRpcProvider(RPC_URLS[NEAR_NETWORK].map(url => new JsonRpcProvider({ url }))),
    []
  );
  const [wallet, setWallet] = useState<Wallet | undefined>();
  const [accountId, setAccountId] = useState('');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;
    const onSignIn = (payload: EventMap['wallet:signIn']) => {
      if (cancelled) return;
      setWallet(payload.wallet);
      setAccountId(payload.accounts[0]?.accountId ?? '');
    };
    const onSignOut = () => {
      if (cancelled) return;
      setWallet(undefined);
      setAccountId('');
    };
    connector.on('wallet:signIn', onSignIn);
    connector.on('wallet:signOut', onSignOut);
    connector.getConnectedWallet()
      .then(connected => {
        if (!cancelled && connected) {
          setWallet(connected.wallet);
          setAccountId(connected.accounts[0]?.accountId ?? '');
        }
      })
      .catch(() => undefined)
      .finally(() => { if (!cancelled) setLoading(false); });
    return () => {
      cancelled = true;
      connector.off('wallet:signIn', onSignIn);
      connector.off('wallet:signOut', onSignOut);
    };
  }, [connector]);

  const signIn = useCallback(async () => {
    const connected = await connector.connect();
    setWallet(connected);
    const accounts = await connected.getAccounts();
    setAccountId(accounts[0]?.accountId ?? '');
  }, [connector]);

  const signOut = useCallback(async () => {
    if (!wallet) return;
    await connector.disconnect(wallet);
    setWallet(undefined);
    setAccountId('');
  }, [connector, wallet]);

  const view = useCallback(
    async <T,>(contractId: string, method: string, args: Record<string, unknown> = {}) =>
      (await rpc.callFunction({ contractId, method, args })) as T,
    [rpc]
  );

  const call = useCallback(
    async (contractId: string, calls: FunctionCall[]) => {
      if (!wallet) throw new Error('Connect a wallet first');
      const outcome = await wallet.signAndSendTransaction({
        receiverId: contractId,
        actions: calls.map(c => ({
          type: 'FunctionCall' as const,
          params: { methodName: c.methodName, args: c.args ?? {}, gas: c.gas ?? DEFAULT_GAS, deposit: c.deposit ?? '0' },
        })),
      });
      return { hash: outcome.transaction.hash, result: getTransactionLastResult(outcome) };
    },
    [wallet]
  );

  const value = useMemo(
    () => ({ loading, accountId, network: NEAR_NETWORK, signIn, signOut, view, call }),
    [loading, accountId, signIn, signOut, view, call]
  );
  return <NearContext.Provider value={value}>{children}</NearContext.Provider>;
}

export function useNearWallet(): NearContextValue {
  const context = useContext(NearContext);
  if (!context) throw new Error('useNearWallet must be used inside <NearProvider>');
  return context;
}
`;
}

export function connectButton(providerImport: string): string {
  return `'use client';
// Generated by APIX. Sign in / sign out with the user's NEAR wallet.
import { useNearWallet } from '${providerImport}';

export function ConnectWallet() {
  const { loading, accountId, signIn, signOut } = useNearWallet();
  if (loading) return <button disabled>Loading…</button>;
  if (!accountId) return <button onClick={() => void signIn()}>Connect NEAR wallet</button>;
  return (
    <span>
      {accountId} <button onClick={() => void signOut()}>Sign out</button>
    </span>
  );
}
`;
}

export function tokenModule(configImport: string): string {
  return `// Generated by APIX (apix add token --chain near).
// Read-only helpers for a NEP-141 token. Safe on the server and in the browser:
// no keys involved. Amounts are strings in the token's smallest unit.
import { JsonRpcProvider } from 'near-api-js';
import { NEAR_NETWORK, NEAR_TOKEN_ID, RPC_URLS } from '${configImport}';

export interface TokenMetadata {
  spec: string;
  name: string;
  symbol: string;
  decimals: number;
  icon: string | null;
}

const rpc = () => new JsonRpcProvider({ url: RPC_URLS[NEAR_NETWORK][0] });

function tokenId(id?: string): string {
  const token = id ?? NEAR_TOKEN_ID;
  if (!token) throw new Error('No token: set NEXT_PUBLIC_NEAR_TOKEN_ID (apix near token create prints it).');
  return token;
}

export async function getTokenMetadata(id?: string): Promise<TokenMetadata> {
  return (await rpc().callFunction({ contractId: tokenId(id), method: 'ft_metadata', args: {} })) as unknown as TokenMetadata;
}

export async function getTokenBalance(accountId: string, id?: string): Promise<string> {
  return ((await rpc().callFunction({ contractId: tokenId(id), method: 'ft_balance_of', args: { account_id: accountId } })) as string) ?? '0';
}

/** True when the account can receive the token (NEP-145 storage registration) */
export async function isRegistered(accountId: string, id?: string): Promise<boolean> {
  const balance = await rpc().callFunction({ contractId: tokenId(id), method: 'storage_balance_of', args: { account_id: accountId } });
  return balance !== null && balance !== undefined;
}

export async function registrationCost(id?: string): Promise<string> {
  const bounds = (await rpc().callFunction({ contractId: tokenId(id), method: 'storage_balance_bounds', args: {} })) as unknown as { min: string };
  return bounds.min;
}

/** "12.5" with 2 decimals -> "1250"; refuses more decimals than the token has */
export function toUnits(amount: string, decimals: number): string {
  const text = amount.trim();
  if (!/^\\d+(\\.\\d+)?$/.test(text)) throw new Error(\`Invalid amount: \${text}\`);
  const [whole, frac = ''] = text.split('.');
  if (frac.length > decimals) throw new Error(\`At most \${decimals} decimals\`);
  return (BigInt(whole + frac.padEnd(decimals, '0'))).toString();
}

/** "1250" with 2 decimals -> "12.5" */
export function fromUnits(units: string, decimals: number): string {
  const padded = units.padStart(decimals + 1, '0');
  const whole = padded.slice(0, padded.length - decimals) || '0';
  const frac = decimals > 0 ? padded.slice(padded.length - decimals).replace(/0+$/, '') : '';
  return frac ? \`\${whole}.\${frac}\` : whole;
}
`;
}

export function tokenRoute(tokenImport: string): string {
  return `// Generated by APIX. Read-only: balances and metadata are public on-chain.
// GET /api/token?account=alice.testnet
import { NextResponse } from 'next/server';
import { getTokenBalance, getTokenMetadata, fromUnits } from '${tokenImport}';

const ACCOUNT_RE = /^(([a-z\\d]+[-_])*[a-z\\d]+\\.)*([a-z\\d]+[-_])*[a-z\\d]+$/;

export async function GET(request: Request) {
  const account = new URL(request.url).searchParams.get('account') ?? '';
  try {
    const metadata = await getTokenMetadata();
    if (!account) return NextResponse.json({ metadata });
    if (!ACCOUNT_RE.test(account) || account.length > 64) {
      return NextResponse.json({ error: 'invalid account id' }, { status: 400 });
    }
    const balance = await getTokenBalance(account);
    return NextResponse.json({ metadata, account, balance, formatted: fromUnits(balance, metadata.decimals) });
  } catch (error) {
    return NextResponse.json({ error: error instanceof Error ? error.message : 'token unavailable' }, { status: 502 });
  }
}
`;
}

export function tokenPanel(providerImport: string, tokenImport: string, configImport: string): string {
  return `'use client';
// Generated by APIX. Shows the user's token balance and sends tokens from
// their own wallet. Handles NEP-145 registration: if the receiver can't hold
// the token yet, the same transaction registers it first (the sender pays the
// small storage deposit), so the transfer can't fail for that reason.
import { useCallback, useEffect, useState } from 'react';
import { useNearWallet } from '${providerImport}';
import { getTokenMetadata, getTokenBalance, isRegistered, registrationCost, toUnits, fromUnits, type TokenMetadata } from '${tokenImport}';
import { EXPLORER, NEAR_NETWORK, NEAR_TOKEN_ID } from '${configImport}';

export function TokenPanel() {
  const { accountId, call } = useNearWallet();
  const [meta, setMeta] = useState<TokenMetadata | null>(null);
  const [balance, setBalance] = useState('0');
  const [to, setTo] = useState('');
  const [amount, setAmount] = useState('');
  const [status, setStatus] = useState('');

  const refresh = useCallback(async () => {
    const m = await getTokenMetadata();
    setMeta(m);
    if (accountId) setBalance(await getTokenBalance(accountId));
  }, [accountId]);

  useEffect(() => { refresh().catch(e => setStatus(String(e?.message ?? e))); }, [refresh]);

  const send = async () => {
    if (!meta) return;
    try {
      setStatus('Waiting for your wallet…');
      const units = toUnits(amount, meta.decimals);
      if (BigInt(units) <= BigInt(0)) throw new Error('Amount must be more than 0');
      if (BigInt(units) > BigInt(balance)) throw new Error('Not enough tokens');
      const calls = [];
      if (!(await isRegistered(to))) {
        calls.push({ methodName: 'storage_deposit', args: { account_id: to, registration_only: true }, deposit: await registrationCost() });
      }
      // NEP-141 requires exactly 1 yoctoNEAR on ft_transfer, which forces a wallet confirmation
      calls.push({ methodName: 'ft_transfer', args: { receiver_id: to, amount: units }, deposit: '1' });
      const { hash } = await call(NEAR_TOKEN_ID, calls);
      setStatus(\`Sent. \${EXPLORER[NEAR_NETWORK]}/txns/\${hash}\`);
      setAmount('');
      await refresh();
    } catch (error) {
      setStatus(error instanceof Error ? error.message : String(error));
    }
  };

  if (!meta) return <div>Loading token…</div>;
  return (
    <section style={{ border: '1px solid #ddd', borderRadius: 8, padding: 16, maxWidth: 420, fontFamily: 'system-ui' }}>
      <h3 style={{ margin: 0 }}>{meta.name} ({meta.symbol})</h3>
      {!accountId ? <p>Connect a wallet to see your balance.</p> : (
        <>
          <p>Your balance: {fromUnits(balance, meta.decimals)} {meta.symbol}</p>
          <input placeholder="receiver.testnet" value={to} onChange={e => setTo(e.target.value.trim())} />
          <input placeholder="amount" value={amount} onChange={e => setAmount(e.target.value)} />
          <button onClick={() => void send()} disabled={!to || !amount}>Send</button>
        </>
      )}
      {status && <p style={{ fontSize: 13, wordBreak: 'break-all' }}>{status}</p>}
    </section>
  );
}
`;
}
